#!/usr/bin/env node
/**
 * Regenerates `src/lib/game/hires-plates.ts` from what is actually on disk.
 *
 * A location plate in `public/locations/<id>.jpg` may have a larger companion
 * in `public/locations/hires/<id>.jpg`. The viewer can only offer the larger
 * one through `srcset` if it knows both widths, and the browser has no way to
 * discover the pair at runtime — so the pairs are compiled into a manifest
 * here and `src/lib/game/scene.test.ts` fails if it drifts from the directory.
 *
 * Run after adding or replacing a hires plate:  node scripts/build-hires-manifest.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PLATES = join(root, "public", "locations");
const HIRES = join(PLATES, "hires");
const OUT = join(root, "src", "lib", "game", "hires-plates.ts");

/**
 * Width of a baseline JPEG, read from its first SOF marker.
 * @param {Buffer} bytes
 * @returns {number | null}
 */
export function jpegWidth(bytes) {
  let i = 2;
  while (i + 9 < bytes.length) {
    if (bytes[i] !== 0xff) {
      i += 1;
      continue;
    }
    const marker = bytes[i + 1];
    // Start-of-frame markers carry the dimensions; C4/C8/CC are not frames.
    if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
      return bytes.readUInt16BE(i + 7);
    }
    if (marker === 0xd8 || marker === 0xd9 || (marker >= 0xd0 && marker <= 0xd7)) {
      i += 2;
      continue;
    }
    i += 2 + bytes.readUInt16BE(i + 2);
  }
  return null;
}

/**
 * Every plate under `public/locations` that ships a wider companion.
 * @param {string} [plateDir]
 * @param {string} [hiresDir]
 * @returns {{ id: string, base: number, wide: number }[]}
 */
export function collectPairs(plateDir = PLATES, hiresDir = HIRES) {
  /** @type {string[]} */
  let hires = [];
  try {
    hires = readdirSync(hiresDir).filter((f) => f.endsWith(".jpg")).sort();
  } catch {
    return [];
  }
  /** @type {{ id: string, base: number, wide: number }[]} */
  const pairs = [];
  for (const file of hires) {
    const id = file.slice(0, -".jpg".length);
    const wide = jpegWidth(readFileSync(join(hiresDir, file)));
    let base = null;
    try {
      base = jpegWidth(readFileSync(join(plateDir, file)));
    } catch {
      base = null;
    }
    if (!wide || !base) {
      console.warn(`[hires] skipping ${file}: missing or unreadable base plate`);
      continue;
    }
    if (wide <= base) {
      console.warn(`[hires] skipping ${file}: hires (${wide}px) is not wider than base (${base}px)`);
      continue;
    }
    pairs.push({ id, base, wide });
  }
  return pairs;
}

/** @param {{ id: string, base: number, wide: number }[]} pairs */
function render(pairs) {
  const entries = pairs
    .map((p) => `  ${JSON.stringify(p.id)}: { base: ${p.base}, hires: ${p.wide} },`)
    .join("\n");
  return `// Generated by scripts/build-hires-manifest.mjs — do not edit by hand.
// Run \`node scripts/build-hires-manifest.mjs\` after adding a plate to
// public/locations/hires/.

/** Pixel widths of the plates that ship a larger companion under hires/. */
export const HIRES_PLATES: Record<string, { base: number; hires: number }> = {
${entries}
};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const pairs = collectPairs();
  writeFileSync(OUT, render(pairs));
  console.log(`[hires] wrote ${pairs.length} plate${pairs.length === 1 ? "" : "s"} to ${OUT}`);
}

export { render, PLATES, HIRES, OUT };
