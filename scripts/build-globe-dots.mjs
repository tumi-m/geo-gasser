#!/usr/bin/env node
/**
 * Land dots for the dotted globe (src/components/motion/dot-globe.tsx):
 * an even Fibonacci-sphere sampling of the Earth, kept where it falls on land
 * in src/data/world.json, packed as base64 int16 (lat×100, lon×100) pairs.
 *
 *   node scripts/build-globe-dots.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const N = 9000;
const world = JSON.parse(readFileSync("src/data/world.json", "utf8"));

function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const polys = world.features.flatMap((f) =>
  f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates,
);
const boxes = polys.map((p) => {
  const xs = p[0].map((c) => c[0]);
  const ys = p[0].map((c) => c[1]);
  return [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
});
const onLand = (lon, lat) =>
  polys.some(
    (p, i) =>
      lon >= boxes[i][0] && lon <= boxes[i][2] && lat >= boxes[i][1] && lat <= boxes[i][3] &&
      inRing(lon, lat, p[0]) && !p.slice(1).some((h) => inRing(lon, lat, h)),
  );

const golden = Math.PI * (3 - Math.sqrt(5));
const out = [];
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lon = ((((i * golden * 180) / Math.PI) % 360) + 540) % 360 - 180;
  if (lat < -60) continue; // Antarctica reads as a smear at globe scale
  if (onLand(lon, lat)) out.push(Math.round(lat * 100), Math.round(lon * 100));
}
const b64 = Buffer.from(new Int16Array(out).buffer).toString("base64");
writeFileSync(
  "src/lib/map/globe-dots.ts",
  `// Generated by scripts/build-globe-dots.mjs — ${out.length / 2} land dots. Do not edit.\nexport const GLOBE_DOTS = "${b64}";\n`,
);
console.log(`globe dots: ${out.length / 2}, ${b64.length} chars`);
